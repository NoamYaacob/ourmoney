// Windows-1255 (Hebrew) single-byte codepage -> Unicode code point table,
// for bytes 0x80-0xFF (0x00-0x7F is identical to ASCII). Values taken from
// the official cp1255 mapping. Unassigned code points in the real codepage
// map to U+FFFD (replacement character) rather than being silently dropped
// or guessed.
//
// Kept as its own file/table (not inline in decodeCsvBytes.ts) so the
// mapping itself is easy to audit and re-verify independently of the
// detection heuristic that decides WHEN to use it.

const REPLACEMENT = 0xfffd

// Index 0 = byte 0x80, index 127 = byte 0xFF.
export const WINDOWS_1255_TABLE: readonly number[] = [
  0x20ac, REPLACEMENT, 0x201a, 0x0192, 0x201e, 0x2026, 0x2020, 0x2021, // 0x80-0x87
  0x02c6, 0x2030, REPLACEMENT, 0x2039, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, // 0x88-0x8F
  REPLACEMENT, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, // 0x90-0x97
  0x02dc, 0x2122, REPLACEMENT, 0x203a, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, // 0x98-0x9F
  0x00a0, 0x00a1, 0x00a2, 0x00a3, 0x20aa, 0x00a5, 0x00a6, 0x00a7, // 0xA0-0xA7 (0xA4 = ₪ New Sheqel sign)
  0x00a8, 0x00a9, 0x00d7, 0x00ab, 0x00ac, 0x00ad, 0x00ae, 0x00af, // 0xA8-0xAF
  0x00b0, 0x00b1, 0x00b2, 0x00b3, 0x00b4, 0x00b5, 0x00b6, 0x00b7, // 0xB0-0xB7
  0x00b8, 0x00b9, 0x00f7, 0x00bb, 0x00bc, 0x00bd, 0x00be, 0x00bf, // 0xB8-0xBF
  0x05b0, 0x05b1, 0x05b2, 0x05b3, 0x05b4, 0x05b5, 0x05b6, 0x05b7, // 0xC0-0xC7
  0x05b8, 0x05b9, REPLACEMENT, 0x05bb, 0x05bc, 0x05bd, 0x05be, 0x05bf, // 0xC8-0xCF
  0x05c0, 0x05c1, 0x05c2, 0x05c3, 0x05f0, 0x05f1, 0x05f2, 0x05f3, // 0xD0-0xD7
  0x05f4, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, REPLACEMENT, // 0xD8-0xDF
  0x05d0, 0x05d1, 0x05d2, 0x05d3, 0x05d4, 0x05d5, 0x05d6, 0x05d7, // 0xE0-0xE7
  0x05d8, 0x05d9, 0x05da, 0x05db, 0x05dc, 0x05dd, 0x05de, 0x05df, // 0xE8-0xEF
  0x05e0, 0x05e1, 0x05e2, 0x05e3, 0x05e4, 0x05e5, 0x05e6, 0x05e7, // 0xF0-0xF7
  0x05e8, 0x05e9, 0x05ea, REPLACEMENT, REPLACEMENT, 0x200e, 0x200f, REPLACEMENT, // 0xF8-0xFF
]

export function decodeWindows1255(bytes: Uint8Array): string {
  let result = ''
  for (const byte of bytes) {
    result += String.fromCodePoint(byte < 0x80 ? byte : WINDOWS_1255_TABLE[byte - 0x80]!)
  }
  return result
}
